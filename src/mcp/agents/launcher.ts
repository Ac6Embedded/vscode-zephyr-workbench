// What an agent actually spawns.
//
// Every agent config points at a stable launcher path, never at a port or a
// token, and never at a versioned extension directory. The launcher is
// rewritten on every activation because the editor runtime path moves: the
// VS Code Server path carries a commit hash and snap installs carry a revision.

import * as path from 'path';
import { normalizeForCompare } from '../core/argSafety';
import { BRIDGE_NAME, defaultMcpHome, LAUNCHER_NAME, MCP_HOME_ENV, McpPaths } from '../core/paths';

export interface LauncherSpec {
  command: string;
  args: string[];
  env: Record<string, string>;
}

/**
 * Prefer the editor's own runtime, so the user needs no Node install. Verified
 * on macOS: VS Code's plugin helper run with ELECTRON_RUN_AS_NODE reports a
 * modern Node. A `node` on PATH is the fallback.
 */
export function posixLauncherScript(paths: McpPaths, execPath: string, version: string): string {
  return [
    '#!/bin/sh',
    `# Generated by Zephyr Workbench ${version}. Rewritten on every VS Code start. Do not edit.`,
    '# Starts the Zephyr Workbench MCP bridge on the editor runtime, falling back to node.',
    'ZW_DIR="$(cd "$(dirname "$0")" && pwd)"',
    '# The bridge finds window records next to itself, wherever this folder is.',
    'ZW_MCP_HOME="$ZW_DIR"',
    'export ZW_MCP_HOME',
    `ZW_NODE='${execPath.replace(/'/g, "'\\''")}'`,
    'if [ -x "$ZW_NODE" ]; then',
    `  ELECTRON_RUN_AS_NODE=1 exec "$ZW_NODE" "$ZW_DIR/${BRIDGE_NAME}" "$@"`,
    'fi',
    `exec node "$ZW_DIR/${BRIDGE_NAME}" "$@"`,
    '',
  ].join('\n');
}

/**
 * The spec written into an agent config.
 *
 * On Windows the editor binary is named directly rather than through a .cmd
 * shim, because several clients spawn shims unreliably.
 */
export function launcherSpec(
  paths: McpPaths, execPath: string, runtime: 'auto' | 'vscode' | 'node', nodePath = 'node',
  platform: NodeJS.Platform = process.platform,
): LauncherSpec {
  // A bridge started without the POSIX launcher cannot tell where a custom
  // home folder is, so the config has to say.
  const homeEnv: Record<string, string> =
    normalizeForCompare(paths.home, platform) === normalizeForCompare(defaultMcpHome(), platform)
      ? {}
      : { [MCP_HOME_ENV]: paths.home };
  const bridge = path.join(paths.home, BRIDGE_NAME);
  if (runtime === 'node') {
    return { command: nodePath, args: [bridge], env: homeEnv };
  }
  if (platform === 'win32') {
    return { command: execPath, args: [bridge], env: { ELECTRON_RUN_AS_NODE: '1', ...homeEnv } };
  }
  // The launcher sets the home from its own location.
  return { command: path.join(paths.home, LAUNCHER_NAME), args: [], env: {} };
}
